#!/usr/bin/env node
// Copies the libraries and fonts the page uses from node_modules into vendor/, so the site
// serves them itself instead of loading them from outside servers. vendor/ is committed; run
// `npm run vendor` after changing a version in package.json (a test checks they match).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NM = path.join(ROOT, 'node_modules');
const OUT = path.join(ROOT, 'vendor');

// Published name in vendor/ → file in node_modules.
const FILES = {
  'react.production.min.js': 'react/umd/react.production.min.js',
  'react-dom.production.min.js': 'react-dom/umd/react-dom.production.min.js',
  'react-is.production.min.js': 'react-is/umd/react-is.production.min.js',
  'Recharts.js': 'recharts/umd/Recharts.js',
  'htm.umd.js': 'htm/dist/htm.umd.js',
  'html2canvas-pro.min.js': 'html2canvas-pro/dist/html2canvas-pro.min.js',
  'xlsx.full.min.js': 'xlsx/dist/xlsx.full.min.js',
  // Reading receipt photos in the browser (loaded only when a receipt is read): the library,
  // its worker, the engine for browsers with and without SIMD, and the English text model.
  'tesseract/tesseract.min.js': 'tesseract.js/dist/tesseract.min.js',
  'tesseract/worker.min.js': 'tesseract.js/dist/worker.min.js',
  'tesseract/core/tesseract-core-lstm.wasm.js': 'tesseract.js-core/tesseract-core-lstm.wasm.js',
  'tesseract/core/tesseract-core-simd-lstm.wasm.js': 'tesseract.js-core/tesseract-core-simd-lstm.wasm.js',
  'tesseract/core/tesseract-core-relaxedsimd-lstm.wasm.js': 'tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm.js',
  'tesseract/lang/eng.traineddata.gz': '@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz',
};
// Font family → [package, weights]. Latin only, which covers English text and the $ and € signs.
const FONTS = {
  'IBM Plex Sans': ['ibm-plex-sans', [400, 500, 600]],
  'IBM Plex Sans Condensed': ['ibm-plex-sans-condensed', [500, 600]],
  'IBM Plex Mono': ['ibm-plex-mono', [400, 500]],
};

function plan() {
  const out = Object.entries(FILES).map(([name, from]) => ({ name, from: path.join(NM, from) }));
  let css = '/* Generated by scripts/vendor.js from the @fontsource packages. */\n';
  for (const [family, [pkg, weights]] of Object.entries(FONTS)) {
    for (const w of weights) {
      const file = `${pkg}-latin-${w}-normal.woff2`;
      out.push({ name: `fonts/${file}`, from: path.join(NM, '@fontsource', pkg, 'files', file) });
      css += `@font-face { font-family: '${family}'; font-style: normal; font-weight: ${w}; font-display: swap; src: url(fonts/${file}) format('woff2'); }\n`;
    }
  }
  return { files: out, css };
}

module.exports = { plan, FILES, OUT };

if (require.main === module) {
  const { files, css } = plan();
  const missing = files.filter((f) => !fs.existsSync(f.from));
  if (missing.length) {
    console.error(`Missing ${missing.map((f) => path.relative(ROOT, f.from)).join(', ')}. Run npm install first.`);
    process.exit(1);
  }
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });
  for (const f of files) { fs.mkdirSync(path.dirname(path.join(OUT, f.name)), { recursive: true }); fs.copyFileSync(f.from, path.join(OUT, f.name)); }
  fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
  console.log(`Copied ${files.length} files into vendor/`);
}
